#!/usr/bin/env python3
"""Embeds assets/catalog/default_catalog.json in the sales app.

The sample catalogue has to be available the instant the app starts, offline,
before anything has been downloaded; generating a Dart constant is simpler
than loading an asset asynchronously everywhere a price is needed. A test
(test/default_catalog_test.dart) fails when this file is out of date:

    python tool/gen_default_catalog.py
"""
import json
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
source = root / "assets" / "catalog" / "default_catalog.json"
target = root / "lib" / "features" / "catalog" / "default_catalog.g.dart"

text = json.dumps(json.loads(source.read_text(encoding="utf-8")), indent=2, ensure_ascii=False)
assert "'''" not in text
target.write_text(
    "// GENERATED by tool/gen_default_catalog.py from assets/catalog/default_catalog.json.\n"
    "// Do not edit: change the JSON and run the script.\n"
    "// ignore_for_file: lines_longer_than_80_chars\n\n"
    "/// The sample catalogue, as JSON.\n"
    f"const String kDefaultCatalogJson = r'''{text}''';\n",
    encoding="utf-8",
)
print(f"wrote {target.relative_to(root)}")
